totfiles

% Para cada archivo vamos a calcular las nuevas coordenas. Primero de
% normalizar en traslación y luego de normalizar en escala.

sizef=zeros(totfiles,1);

for j=1:totfiles

    j %Impresión del número de archivo

    B=[];

    % Procesamos el j-esimo archivo
    temp=char(files(j));
    fp=fopen(temp);
    if (fp>0)
        A=fscanf(fp,'%e');

        B=[B; A];
        fclose(fp);
    end

    % Bloque para cuando trae 3 coordenadas el archivo pcd en txt.
    N=size(B,1)/3;

    sizef(j)=N;

    B=reshape(B,3,N);

    B=B';

    X=B(:,1);
    Y=B(:,2);
    Z=B(:,3);

   
    %%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
    % 3D plot
    figure;
    h=plot3(X,Z,Y,'b.');
    grid;
    axis square;
    hold on;

    % Display statistics
    % Print the number of points
    fprintf('N= %d\n',N);
    fprintf('\nCoordinate Statistics:\n');
    fprintf('X - Min: %.4f, Max: %.4f, Mean: %.4f\n', min(X), max(X), mean(X));
    fprintf('Y - Min: %.4f, Max: %.4f, Mean: %.4f\n', min(Y), max(Y), mean(Y));
    fprintf('Z - Min: %.4f, Max: %.4f, Mean: %.4f\n', min(Z), max(Z), mean(Z));

    % Graficamos el centroide de la nube 3D
    %     plot3(xc3,zc3,yc3,'b.');

    % Normalize the coordinates
    Xc=mean(X);
    Yc=mean(Y);
    Zc=mean(Z);
      
    Xtr = (X - mean(X));
    Ytr = (Y - mean(Y));
    Ztr = (Z - mean(Z));

     % Display statistics
    % Print the number of points
    fprintf('N= %d\n',N);
    fprintf('\nCoordinate Statistics:\n');
    fprintf('Xtr - Min: %.4f, Max: %.4f, Mean: %.4f\n', min(Xtr), max(Xtr), mean(Xtr));
    fprintf('Ytr - Min: %.4f, Max: %.4f, Mean: %.4f\n', min(Ytr), max(Ytr), mean(Ytr));
    fprintf('Ztr - Min: %.4f, Max: %.4f, Mean: %.4f\n', min(Ztr), max(Ztr), mean(Ztr));


    normVal = zeros(N, 1);  % Initialize normVal as a column vector
    % Calculate the centroid of the translated coordinates
    centroid = [Xc, Yc, Zc];

    % Plot the centroid on the 3D scatter plot
    plot3(centroid(1), centroid(3), centroid(2), 'ro', 'MarkerSize', 10, 'MarkerFaceColor', 'r');

    % Search the point with the maximum norm
    for i=1:N
        % Calculate the norm of the translated coordinates
        normVal(i) = sqrt(Xtr(i)^2 + Ytr(i)^2 + Ztr(i)^2);
    end;

    % Calculate the maximum norm value and its index
    [maxNorm, maxIndex] = max(normVal);
    fprintf('Max Norm: %.4f at index %d\n', maxNorm, maxIndex);

    % Calculate the new coordinates that fit inside a sphere of radius 1
    Xs = Xtr/maxNorm;
    Ys = Ytr/maxNorm;
    Zs = Ztr/maxNorm;

     % Display statistics
    % Print the number of points
    fprintf('N= %d\n',N);
    fprintf('\nCoordinate Statistics:\n');
    fprintf('Xs - Min: %.4f, Max: %.4f, Mean: %.4f\n', min(Xs), max(Xs), mean(Xs));
    fprintf('Ys - Min: %.4f, Max: %.4f, Mean: %.4f\n', min(Ys), max(Ys), mean(Ys));
    fprintf('Zs - Min: %.4f, Max: %.4f, Mean: %.4f\n', min(Zs), max(Zs), mean(Zs));

    % Print a new file the normalized cloud point in translation and scale
    % Save the normalized coordinates to a new file
    outputFileName = sprintf('normalized_%d.txt', j);
    outputFile = fopen(outputFileName, 'w');
    if outputFile > 0
        fprintf(outputFile, '%f %f %f\n', [Xs, Ys, Zs]');
        fclose(outputFile);
    else
        warning('Could not open file: %s', outputFileName);
    end

end;

